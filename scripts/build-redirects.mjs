#!/usr/bin/env node
/**
 * Generates public/_redirects for Cloudflare Pages.
 *
 * The map is authored below in readable Arabic script and percent-encoded on
 * write, for the same reason src/i18n/routes.ts does it: hand-typing
 * %D8%A7%D9%84... is how a redirect map acquires silent typos.
 *
 * Source of truth for what is being redirected and why: docs/legacy-urls.md
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

/** [from, to, status] — `from` is the live WordPress URL, `to` is the new one. */
const REDIRECTS = [
  // --- English -------------------------------------------------------------
  // /work/ is not built yet, so portfolio traffic goes to the services index
  // rather than 301-ing into a 404. Restore this when the case studies land.
  ['/portfolio/', '/services/', 301],

  // --- Arabic: services index and details -----------------------------------
  ['/ar/خدماتنا/', '/ar/الخدمات/', 301],
  ['/ar/خدماتنا/تصميم-المواقع/', '/ar/الخدمات/تصميم-وتطوير-المواقع/', 301],
  ['/ar/خدماتنا/تحسين-محركات-البحث/', '/ar/الخدمات/تحسين-محركات-البحث/', 301],
  ['/ar/خدماتنا/الملف-التجاري-جوجل/', '/ar/الخدمات/تحسين-الملف-التجاري-على-جوجل/', 301],
  ['/ar/خدماتنا/التصميم-الجرافيكي/', '/ar/الخدمات/التصميم-الجرافيكي/', 301],
  ['/ar/خدماتنا/إدارة-المتاجر-الإلكترونية/', '/ar/الخدمات/إدارة-المتاجر-الإلكترونية/', 301],

  // --- Arabic: free audit ---------------------------------------------------
  ['/ar/تقييم-مجاني/', '/ar/تدقيق-مجاني/', 301],

  // --- WordPress leftovers --------------------------------------------------
  ['/hello-world/', '/blog/', 301],
  ['/category/blog/', '/blog/', 301],

  // NOTE: /privacy-policy/ deliberately has no rule. The new /privacy/ page is
  // not written yet, and a 301 to a missing page is worse than a clean 404.
  // Add the rule in the same commit that adds the page.

  // --- WordPress surface that should never have been public -----------------
  ['/wp-admin/*', '/', 301],
  ['/wp-login.php', '/', 301],
  ['/feed/', '/blog/', 301],
  ['/comments/feed/', '/blog/', 301],
]

const encodePath = (path) =>
  path
    .split('/')
    .map((segment) => (segment ? encodeURIComponent(segment).replace(/%2A/g, '*') : segment))
    .join('/')

// Percent-encoded Arabic makes column alignment unreadable, so each rule is
// preceded by a comment showing the decoded form.
const body = REDIRECTS.map(([from, to, status]) => {
  const rule = `${encodePath(from)} ${encodePath(to)} ${status}`
  const readable = from === encodePath(from) ? '' : `# ${from} -> ${to}\n`
  return `${readable}${rule}`
}).join('\n')

const output = `# Generated by scripts/build-redirects.mjs — do not edit by hand.
# Source map and rationale: docs/legacy-urls.md

${body}
`

const target = join(process.cwd(), 'public', '_redirects')
await mkdir(dirname(target), { recursive: true })
await writeFile(target, output, 'utf8')

console.log(`✓ Wrote ${REDIRECTS.length} redirects to public/_redirects`)
